// Derived stat calculations — used by the inventory page stat cards
export function getInventoryStats(stock: DrugStock[]) {
  return {
    productCount: stock.length,
    nearExpiry: stock.filter(s => {
      const daysToExpiry = (new Date(s.expiryDate).getTime() - Date.now()) / (1000 * 60 * 60 * 24);
      return daysToExpiry > 0 && daysToExpiry <= 90;
    }).length,
    stockOuts: stock.filter(s => s.quantity === 0).length,
    lowStock: stock.filter(s => s.lowStockAlert && s.quantity > 0).length,
  };
}
